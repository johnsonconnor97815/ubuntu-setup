#!/usr/bin/env bash
#
# scripts/rime.sh — install / configure / manage the RIME input method (on fcitx5) on Ubuntu.
#
# RIME (https://rime.im) is a highly-configurable input method engine for Chinese / CJK.
# On Ubuntu it rides on the fcitx5 input-method framework (the community-preferred carrier).
# This script is a *component manager* (like scripts/zsh.sh / scripts/tmux.sh): it installs
# fcitx5 + the RIME engine + frontends, selects the framework, writes the environment that
# lets apps talk to fcitx5, and manages which RIME schemas (输入方案) are enabled — with an
# opt-in for the popular 雾凇拼音 (rime-ice) config. Everything is user-space; only apt needs
# root (escalated per-command via the shared library), never whole-root, never `sudo npm`.
#
# Install channels: apt only (fcitx5 + RIME are in the official Ubuntu repos).
#
# Configuration model (mirrors scripts/ghostty.sh's managed drop-in):
#   - Preferences live in ~/.config/ubuntu-setup/rime.conf (the kit's KEY=VALUE store).
#   - From them we regenerate a managed RIME patch ~/.local/share/fcitx5/rime/default.custom.yaml
#     (we own it; rewritten wholesale + convergent; backed up before the first overwrite).
#   - The fcitx5 input-method environment is a managed file we own too:
#     ~/.config/environment.d/ubuntu-setup-rime.conf (GTK/QT/XMODIFIERS).
#   - A managed XDG autostart entry ~/.config/autostart/org.fcitx.Fcitx5.desktop launches
#     fcitx5 at login. This is REQUIRED on Wayland (Ubuntu's default): im-config/im-launch
#     only starts the IM daemon for X11 sessions (its Wayland branch is disabled) and the
#     fcitx5 package ships no /etc/xdg/autostart entry — so without it nothing starts fcitx5
#     and the desktop keeps falling back to its built-in IBus.
#   - Fuzzy pinyin (模糊音) is a *per-schema* speller/algebra feature, so it cannot live in
#     default.custom.yaml (that patches the GLOBAL default — schema_list/menu). Instead we
#     manage a small per-schema patch ~/.local/share/fcitx5/rime/<schema>.custom.yaml for each
#     enabled pinyin schema (rime_ice when 雾凇拼音 is active, else the luna_pinyin family),
#     appending the chosen fuzzy rules via 'speller/algebra/+' so we never have to reproduce a
#     schema's full algebra. We own only files carrying our marker; a user's own <schema>.custom
#     .yaml is backed up before we take it over, and our files are removed when fuzzy is cleared.
#
# Honesty note: RIME/fcitx5 is a *desktop* input method. Over SSH / on a headless server you
# are not running a graphical session on this box — these settings apply where the desktop
# actually runs (a machine with a display), and take effect after the next login. install /
# configure / deploy say so when they detect an SSH session or no display.
#
# Run it as:  rime.sh install|remove|configure|deploy|status|ui|meta|help   (or via `swkit`).

set -Eeuo pipefail

# Locate and load the shared library (scripts/ sits next to lib/ under the kit root).
_kit_here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../lib/common.sh
source "$_kit_here/lib/common.sh"

# --- Curated knowledge ---------------------------------------------------------
readonly _RIME_ICE_REPO="https://github.com/iDvel/rime-ice.git"
# fcitx5-rime bundles rime-data (brise), so these schemas need no extra download.
readonly _RIME_CURATED=(
  luna_pinyin_simp luna_pinyin luna_pinyin_fluency
  double_pinyin_flypy double_pinyin bopomofo
  wubi86 wubi_pinyin cangjie5 stroke terra_pinyin
)

# Curated fuzzy-pinyin (模糊音) pairs. Each key maps (via _rime_fuzzy_rules) to one or more RIME
# `derive` rules that get appended to a pinyin schema's speller/algebra. These mirror the (commented)
# fuzzy block that rime-ice ships in rime_ice.schema.yaml, so enabling them here matches upstream.
readonly _RIME_FUZZY=(
  zh_z n_l f_h l_r g_k
  in_ing en_eng an_ang ian_iang uan_uang
)

# The full-pinyin schemas a fuzzy patch can target. Full pinyin only: double-pinyin schemas map
# keystrokes, not full-pinyin spellings, so these `derive` rules don't apply to them; non-pinyin
# schemas (wubi/cangjie/stroke/bopomofo) have no concept of 模糊音. We iterate this fixed set when
# converging/cleaning per-schema fuzzy files (so stale ones are removed when schemas change).
readonly _RIME_FUZZY_SCHEMAS=(
  luna_pinyin_simp luna_pinyin luna_pinyin_fluency terra_pinyin rime_ice
)

# First line of every fuzzy <schema>.custom.yaml we generate — lets us tell our files from a
# user's own (we only ever overwrite/remove a file whose first line carries this marker).
readonly _RIME_FUZZY_MARK='# Generated by ubuntu-setup (swkit rime)'

# fcitx5's GNOME-on-Wayland "self-diagnose" notification nags at EVERY login to install the
# kimpanel GNOME Shell extension (https://fcitx-im.org/wiki/Using_Fcitx_5_on_Wayland#GNOME).
# RIME works fine without kimpanel, so for most users it's pure noise. fcitx5 hides a tip
# permanently when its id is listed under [HiddenNotifications] in notifications.conf — exactly
# what its "Do not show again" button writes. This is that GNOME tip's id (see _rime_apply_diagnose_silence).
readonly _RIME_WAYLAND_DIAGNOSE_TIP='wayland-diagnose-gnome'

# Echo the RIME speller/algebra `derive` rule(s) for one fuzzy pair, one per line. Single-quoted
# so $1/$2/$ stay literal (they are RIME regex back-references, not shell expansions — that is the
# whole point here, so SC2016's "expressions don't expand in single quotes" note is expected).
# shellcheck disable=SC2016
_rime_fuzzy_rules() {
  case "$1" in
    zh_z)     printf '%s\n' 'derive/^([zcs])h/$1/' 'derive/^([zcs])([^h])/$1h$2/' ;;
    n_l)      printf '%s\n' 'derive/^n/l/' 'derive/^l/n/' ;;
    f_h)      printf '%s\n' 'derive/^f/h/' 'derive/^h/f/' ;;
    l_r)      printf '%s\n' 'derive/^l/r/' 'derive/^r/l/' ;;
    g_k)      printf '%s\n' 'derive/^g/k/' 'derive/^k/g/' ;;
    in_ing)   printf '%s\n' 'derive/in$/ing/' 'derive/ing$/in/' ;;
    en_eng)   printf '%s\n' 'derive/en$/eng/' 'derive/eng$/en/' ;;
    an_ang)   printf '%s\n' 'derive/an$/ang/' 'derive/ang$/an/' ;;
    ian_iang) printf '%s\n' 'derive/ian$/iang/' 'derive/iang$/ian/' ;;
    uan_uang) printf '%s\n' 'derive/uan$/uang/' 'derive/uang$/uan/' ;;
  esac
}

