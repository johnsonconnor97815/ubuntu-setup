  per-schema speller/algebra feature: pairs are appended to each active pinyin schema's
  <schema>.custom.yaml (rime_ice when 雾凇拼音 is on, else the luna_pinyin family) — NOT to the
  global default.custom.yaml. More pairs trade precision for tolerance.
