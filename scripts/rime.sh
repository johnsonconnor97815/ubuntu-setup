_rime_fuzzy_in() { local s; for s in $FUZZY; do [[ "$s" == "$1" ]] && return 0; done; return 1; }
_rime_fuzzy_add() { _rime_fuzzy_in "$1" || FUZZY="${FUZZY:+$FUZZY }$1"; }
_rime_fuzzy_remove() {
  local s out=""
  for s in $FUZZY; do [[ "$s" == "$1" ]] || out="${out:+$out }$s"; done
  FUZZY="$out"
}

# Echo (one per line) the schema ids that should receive the fuzzy patch right now: rime_ice when
# 雾凇拼音 owns the schema list, otherwise the enabled full-pinyin schemas. Used to decide where to
# write — and, by elimination from _RIME_FUZZY_SCHEMAS, where to clean up stale fuzzy files.
_rime_fuzzy_targets() {
  if [[ "${RIME_ICE:-0}" == 1 ]]; then printf '%s\n' rime_ice; return 0; fi
  local s
  for s in $SCHEMAS; do
    case " ${_RIME_FUZZY_SCHEMAS[*]} " in *" $s "*) printf '%s\n' "$s" ;; esac
  done
}

