do_add_schema() {
  [[ $# -ge 1 ]] || { log_err "Usage: rime add-schema <schema-id>  (e.g. bopomofo)"; return 2; }
  _rime_schema_id_valid "$1" || { log_err "Invalid schema id: $1"; return 2; }
  _rime_resolve_home || return 1
